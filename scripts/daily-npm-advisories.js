#!/usr/bin/env node

// Daily triage for Shield's offline npm rules. New advisories create a digest issue;
// no version range is copied into the scanner without checking its conditions.
const fs = require('node:fs');
const path = require('node:path');

const API = 'https://api.github.com';
const repository = process.env.GITHUB_REPOSITORY || 'andrei-gogo/acrionix-shield';
const token = process.env.GITHUB_TOKEN;
const dryRun = process.argv.includes('--dry-run');
const since = new Date(Date.now() - 3 * 24 * 60 * 60 * 1000).toISOString().slice(0, 10);

async function request(url, options = {}) {
  const headers = {
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2026-03-10',
    'User-Agent': 'acrionix-shield-daily-npm-review',
    ...(token ? { Authorization: `Bearer ${token}` } : {}),
    ...options.headers,
  };
  const response = await fetch(url, { ...options, headers });
  if (!response.ok) throw new Error(`GitHub API ${response.status}: ${response.statusText} (${url})`);
  return { data: await response.json(), next: response.headers.get('link')?.match(/<([^>]+)>; rel="next"/)?.[1] };
}

async function advisories(type, severity) {
  const query = new URLSearchParams({ ecosystem: 'npm', type, modified: `>=${since}`, per_page: '100', sort: 'updated' });
  if (severity) query.set('severity', severity);
  let url = `${API}/advisories?${query}`;
  const results = [];
  while (url) {
    const page = await request(url);
    if (!Array.isArray(page.data)) throw new Error('GitHub advisory response was not a list');
    results.push(...page.data);
    url = page.next;
  }
  return results;
}

function coveredIds() {
  const dir = path.join(__dirname, '..', 'src', 'scanners');
  const source = fs.readdirSync(dir).filter(name => name.endsWith('.js'))
    .map(name => fs.readFileSync(path.join(dir, name), 'utf8')).join('\n');
  return new Set(source.match(/GHSA-[a-z0-9]{4}-[a-z0-9]{4}-[a-z0-9]{4}/gi) || []);
}

async function issueExists(title) {
  const query = new URLSearchParams({ q: `repo:${repository} in:title "${title}"` });
  const { data } = await request(`${API}/search/issues?${query}`);
  return data.items.some(issue => issue.title === title);
}

function lineFor(advisory) {
  const packages = advisory.vulnerabilities.filter(item => item.package?.ecosystem === 'npm')
    .map(item => `\`${item.package.name}\` (${item.vulnerable_version_range || '?'}, fix ${item.first_patched_version || '?'})`);
  return `- [${advisory.ghsa_id}](${advisory.html_url}) — ${advisory.type}, ${advisory.severity || 'unrated'} — ${packages.join(', ')}`;
}

function bodyFor(candidates) {
  const shown = candidates.slice(0, 60);
  return [
    `GitHub npm advisories published or updated since ${since} UTC: **${candidates.length} uncovered candidates**.`,
    `Showing the first ${shown.length}, prioritizing reviewed critical/high advisories, then malware. The Actions run summary has the full list.`,
    '',
    ...shown.map(lineFor),
    '',
    'Review maintainer advisories, exploit conditions, exact affected versions and fixes before adding Shield rules. Add regression cases. Do not install suspicious releases to investigate them. This daily review does not publish an npm package automatically.',
    '',
    'Generated by the daily npm advisory review workflow.',
  ].join('\n');
}

async function main() {
  const pages = await Promise.all([
    advisories('reviewed', 'critical'),
    advisories('reviewed', 'high'),
    advisories('malware'),
  ]);
  const covered = coveredIds();
  const unique = new Map();
  for (const item of pages.flat()) {
    if (!item.ghsa_id || item.withdrawn_at || covered.has(item.ghsa_id)) continue;
    if (!item.vulnerabilities?.some(v => v.package?.ecosystem === 'npm')) continue;
    unique.set(item.ghsa_id, item);
  }
  const rank = item => item.type === 'reviewed' ? (item.severity === 'critical' ? 0 : 1) : 2;
  const candidates = [...unique.values()].sort((a, b) => rank(a) - rank(b) || b.updated_at.localeCompare(a.updated_at));
  const title = `Daily npm advisory review ${new Date().toISOString().slice(0, 10)}`;
  let opened = 0;
  if (dryRun) {
    for (const item of candidates.slice(0, 20)) process.stdout.write(`${item.ghsa_id} ${item.severity || item.type} ${item.html_url}\n`);
  } else if (candidates.length && !(await issueExists(title))) {
    await request(`${API}/repos/${repository}/issues`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ title, body: bodyFor(candidates) }),
    });
    opened = 1;
  }
  const summary = `Daily npm advisory review: ${candidates.length} uncovered candidate(s), ${opened} new digest issue(s), window since ${since} UTC.\n`;
  process.stdout.write(summary);
  if (process.env.GITHUB_STEP_SUMMARY) fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY,
    `## ${summary}\n${candidates.map(lineFor).join('\n')}\n`);
}

main().catch(error => { console.error(error.message); process.exitCode = 1; });
